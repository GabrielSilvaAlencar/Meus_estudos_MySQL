# comando AS: renomeando as colunas da sua consulta

select
	ID_Produto 		AS 'ID Produto', 
    Nome_Produto 	AS 'Nome do Produto',
    Marca_Produto 	AS 'Marca do Produto',
    Custo_Unit 		AS 'Custo Unitário'
from produtos;



# OBS: isso não altera nada do tópicos do banco de dados, isso é somante para visualização.
